export const REVISED_QUESTION_IDS=Object.freeze(Object.keys(revisions));
export function applyQuestionRevisions(week) {
  week.retiredQuestions=[];
  week.questions=week.questions.map(old=>{
    const authored=revisions[old.id];if(!authored)return old;
    const [prompt,...choices]=authored;
    if(choices.length!==4)throw new Error(`Four authored choices required: ${old.id}`);
    const answerIndex=['a','b','c','d'].indexOf(old.answerId);
    const options=['a','b','c','d'].map((id,i)=>{
      const pair=choices[(i-answerIndex+4)%4].split('|');
      if(pair.length!==2)throw new Error(`Choice rationale required: ${old.id}`);
      return{id,text:pair[0],explanation:pair[1]};
    });
    const id=`${old.id}-r2`;
    week.retiredQuestions.push({...structuredClone(old),supersededBy:id});
    return{...old,id,family:`${old.family}-r2`,prompt,context:'',kind:'application',difficulty:2,options,explanation:choices[0].split('|')[1]};
  });
}
